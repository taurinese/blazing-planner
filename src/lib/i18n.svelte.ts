export type Lang = 'fr' | 'en';
const dictionaries: Record<Lang, Record<MessageKey, string>> = { fr, en };

const PREFS_KEY = 'nbr-planner:prefs';

function loadPrefs(): { lang: Lang; theme: 'auto' | 'light' | 'dark' } {
  try {
    const p = JSON.parse(localStorage.getItem(PREFS_KEY) ?? '{}');
    return {
      lang: p.lang === 'en' || p.lang === 'fr' ? p.lang : navigator.language.startsWith('fr') ? 'fr' : 'en',
      theme: ['light', 'dark'].includes(p.theme) ? p.theme : 'auto',
    };
  } catch {
    return { lang: 'fr', theme: 'auto' };
  }
}

export const prefs = $state(loadPrefs());

$effect.root(() => {
  $effect(() => {
    const snapshot = JSON.stringify(prefs);
    try { localStorage.setItem(PREFS_KEY, snapshot); } catch { /* prefs are optional */ }
    document.documentElement.lang = prefs.lang;
    if (prefs.theme === 'auto') delete document.documentElement.dataset.theme;
    else document.documentElement.dataset.theme = prefs.theme;
  });
});

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  const template = dictionaries[prefs.lang][key] ?? fr[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

/** Formats an ISO "YYYY-MM-DD" date in the interface language. */
export function fmtDate(iso: string, style: 'long' | 'month' = 'long'): string {
  const options: Intl.DateTimeFormatOptions =
    style === 'month' ? { month: 'long', year: 'numeric', timeZone: 'UTC' } : { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' };
  return new Intl.DateTimeFormat(prefs.lang === 'fr' ? 'fr-FR' : 'en-GB', options).format(new Date(`${iso}T00:00:00Z`));
}

export function fmt(n: number): string {
  return new Intl.NumberFormat(prefs.lang === 'fr' ? 'fr-FR' : 'en-US').format(n);
}
